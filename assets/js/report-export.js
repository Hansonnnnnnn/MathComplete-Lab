  function roundStorageKey() {
    return `${ROUND_KEY_PREFIX}${currentGameId()}`;
  }

  function saveRound() {
    try {
      sessionStorage.setItem(roundStorageKey(), JSON.stringify({ roundStartedAt, attempts: attempts.slice(-MAX_ATTEMPTS) }));
    } catch {
      // In-memory export still works when storage is unavailable.
    }
  }

  function loadRound() {
    try {
      const raw = sessionStorage.getItem(roundStorageKey());
      const parsed = raw ? JSON.parse(raw) : null;
      if (Array.isArray(parsed?.attempts)) {
        attempts = parsed.attempts;
        roundStartedAt = parsed.roundStartedAt || roundStartedAt;
      }
    } catch {
      attempts = [];
    }
  }

  function resetRound() {
    attempts = [];
    roundStartedAt = new Date().toISOString();
    saveRound();
  }

  function questionTextFrom(question, payload) {
    return safe(
      payload?.questionLatex || payload?.question_latex || question?.main ||
      question?.displayExpression || question?.latex || question?.equationText ||
      question?.plain || payload?.questionText || payload?.question_text ||
      question?.expression || ""
    );
  }

  function plainQuestionFrom(question, payload) {
    return safe(
      payload?.questionText || payload?.question_text || question?.plain ||
      question?.equationText || stripHtml(question?.main || question?.displayExpression || question?.latex || "")
    );
  }

  function answerText(value) {
    if (value && typeof value === "object") return safe(value.latex ?? value.text ?? value.value ?? "");
    return safe(value);
  }

  function comparableAnswer(value) {
    return answerText(value).replace(/\s+/g, "");
  }

  function domOptions(selected = "", correct = "") {
    const optionsRoot = document.getElementById("options");
    if (!optionsRoot) return [];
    const selectedKey = comparableAnswer(selected);
    const correctKey = comparableAnswer(correct);
    return [...optionsRoot.querySelectorAll("button, .option")].map((node, index) => {
      const annotation = node.querySelector("annotation[encoding='application/x-tex']")?.textContent;
      const latex = safe(node.dataset?.latex || annotation || node.getAttribute("aria-label") || node.textContent || "").trim();
      const key = comparableAnswer(latex);
      return {
        label: String.fromCharCode(65 + index),
        latex,
        isCorrect: node.classList.contains("correct") || Boolean(correctKey && key === correctKey),
        isSelected: node.classList.contains("wrong") || Boolean(selectedKey && key === selectedKey)
      };
    }).filter(option => option.latex);
  }

  function normalizeOptions(payload = {}, selected = "", correct = "") {
    const question = payload.question || payload.questionSnapshot || {};
    const raw = Array.isArray(payload.options) ? payload.options
      : Array.isArray(payload.answerOptions) ? payload.answerOptions
        : Array.isArray(question.options) ? question.options
          : Array.isArray(question.choices) ? question.choices : [];
    if (!raw.length) return domOptions(selected, correct);
    const selectedKey = comparableAnswer(selected);
    const correctKey = comparableAnswer(correct);
    return raw.map((option, index) => {
      if (option && typeof option === "object") {
        const latex = answerText(option.latex ?? option.text ?? option.value ?? option.answer ?? option);
        const optionKey = comparableAnswer(option.key ?? latex);
        return {
          label: safe(option.label || option.id || String.fromCharCode(65 + index)),
          latex,
          isCorrect: Boolean(option.isCorrect || option.correct || (correctKey && (optionKey === correctKey || comparableAnswer(latex) === correctKey))),
          isSelected: Boolean(option.isSelected || option.selected || (selectedKey && (optionKey === selectedKey || comparableAnswer(latex) === selectedKey)))
        };
      }
      const latex = answerText(option);
      const optionKey = comparableAnswer(latex);
      return {
        label: String.fromCharCode(65 + index),
        latex,
        isCorrect: Boolean(correctKey && optionKey === correctKey),
        isSelected: Boolean(selectedKey && optionKey === selectedKey)
      };
    }).filter(option => option.latex);
  }

  function normalizeAttempt(payload = {}, rawPayload = null) {
    const question = payload.question || payload.questionSnapshot || rawPayload?.question || {};
    const selected = payload.timeUp ? ""
      : (payload.selectedAnswer ?? payload.selectedAnswerLatex ?? payload.selected_answer_latex ?? payload.selected_answer ?? "");
    const correct = payload.correctAnswer ?? payload.correctAnswerLatex ?? payload.correct_answer_latex ?? payload.correct_answer ?? "";
    const options = normalizeOptions(payload, selected, correct);
    const selectedOptionLabel = safe(payload.selectedOptionLabel || payload.selected_option_label || options.find(option => option.isSelected)?.label || "");
    const correctOptionLabel = safe(payload.correctOptionLabel || payload.correct_option_label || options.find(option => option.isCorrect)?.label || "");

    return {
      index: attempts.length + 1,
      gameId: safe(payload.gameId || payload.game_id || currentGameId()),
      toolTitle: currentToolTitle(),
      topic: safe(payload.topic || question.type || question.templateId || question.builder || ""),
      topicLabel: safe(payload.topicLabel || payload.topic_label || question.topicLabel || question.topic_label || ""),
      familyId: safe(payload.familyId || payload.family_id || question.familyId || question.family_id || question.type || ""),
      conceptId: safe(payload.conceptId || payload.concept_id || question.conceptId || question.concept_id || ""),
      templateId: safe(payload.templateId || payload.template_id || question.templateId || question.template_id || ""),
      templateVersion: safe(payload.templateVersion || payload.template_version || question.templateVersion || ""),
      seed: payload.seed ?? question.seed ?? null,
      parameters: payload.parameters || question.parameters || null,
      difficulty: safe(payload.difficulty || question.difficulty || document.getElementById("difficultyText")?.textContent?.trim() || ""),
      questionLatex: questionTextFrom(question, payload),
      questionText: plainQuestionFrom(question, payload),
      selectedAnswerLatex: answerText(selected),
      correctAnswerLatex: answerText(correct),
      options,
      selectedOptionLabel,
      correctOptionLabel,
      isCorrect: Boolean(payload.isCorrect ?? payload.is_correct),
      timeUp: Boolean(payload.timeUp),
      answeredAt: payload.answeredAt || new Date().toISOString(),
      timeSpentSeconds: Number.isFinite(Number(payload.timeSpentSeconds ?? payload.time_spent_seconds))
        ? Math.max(0, Math.round(Number(payload.timeSpentSeconds ?? payload.time_spent_seconds))) : null,
      suggestion: safe(payload.suggestion || question.suggestion || ""),
      visual: payload.visual || question.visual || null
    };
  }

  function rememberAttempt(payload, rawPayload = null) {
    const item = normalizeAttempt(payload, rawPayload);
    if (!item.questionLatex && !item.questionText) return;
    attempts.push(item);
    attempts = attempts.slice(-MAX_ATTEMPTS);
    saveRound();
  }

  function patchProgress() {
    const progress = window.MCLProgress;
    if (!progress || progress.__mclReportPatched) return false;
    if (typeof progress.recordGameAttempt === "function") {
      originalRecordGameAttempt = progress.recordGameAttempt.bind(progress);
      progress.recordGameAttempt = function (payload) {
        rememberAttempt(payload);
        return originalRecordGameAttempt(payload);
      };
    }
    if (typeof progress.recordAttempt === "function") {
      originalRecordAttempt = progress.recordAttempt.bind(progress);
      progress.recordAttempt = function (payload) {
        rememberAttempt(payload);
        return originalRecordAttempt(payload);
      };
    }
    progress.__mclReportPatched = true;
    return true;
  }

  function stats(items = attempts) {
    const total = items.length;
    const correct = items.filter(item => item.isCorrect).length;
    return { total, correct, wrong: total - correct, accuracy: total ? Math.round((correct / total) * 100) : 0 };
  }

  function buildReportModel() {
    loadRound();
    const t = copy();
    const finishedAt = new Date().toISOString();
    const items = attempts.map(item => ({ ...item, options: Array.isArray(item.options) ? item.options.map(option => ({ ...option })) : [] }));
    const startedAt = roundStartedAt;
    const durationSeconds = Math.max(0, Math.round((new Date(finishedAt).getTime() - new Date(startedAt).getTime()) / 1000));
    const wrongItems = items.filter(item => !item.isCorrect);
    const reviewRecommendations = [...new Set(wrongItems.map(item => safe(item.suggestion).trim()).filter(Boolean))].slice(0, 3);
    if (!reviewRecommendations.length && wrongItems.length) reviewRecommendations.push(t.reviewIncorrectQuestions(wrongItems.map(item => item.index)));
    return {
      language: lang(),
      t,
      gameId: currentGameId(),
      reportId: reportIdentifier(currentGameId(), finishedAt),
      learner: { displayName: learnerDisplayName(t) },
      tool: currentToolTitle(),
      mode: currentModeLabel(),
      difficulty: currentDifficultyLabel(),
      timer: currentTimerLabel(t),
      startedAt,
      finishedAt,
      durationSeconds,
      reviewRecommendations,
      stats: stats(items),
      attempts: items
    };
  }

  function syncVisibleResultStats() {
    const resultCard = document.getElementById("resultCard");
    if (!resultCard || resultCard.classList.contains("hidden") || !attempts.length) return;
    const s = stats();
    const values = {
      scoreNum: `${s.correct}/${s.total}`,
      accuracyNum: `${s.accuracy}%`,
      wrongNum: String(s.wrong)
    };
    Object.entries(values).forEach(([id, value]) => {
      const node = document.getElementById(id);
      if (node && node.textContent !== value) node.textContent = value;
    });
  }

  function renderMath(value, blankText = copy().blank) {
    const text = safe(value);
    if (!text) return `<span class="mcl-report-blank">${escapeHtml(blankText)}</span>`;
    return `<span class="mcl-report-math" data-latex="${attr(text)}">${escapeHtml(text)}</span>`;
  }

  function optionsHtml(item, t, segmented = false) {
    if (!Array.isArray(item.options) || !item.options.length) return "";
    const choices = item.options.map(option => {
      const correct = option.isCorrect || (item.correctOptionLabel && option.label === item.correctOptionLabel);
      const selected = option.isSelected || (item.selectedOptionLabel && option.label === item.selectedOptionLabel);
      const badges = [
        correct ? `<span class="mcl-report-choice-badge mcl-report-choice-badge-correct">${escapeHtml(t.correctOptionTag)}</span>` : "",
        selected ? `<span class="mcl-report-choice-badge ${correct ? "mcl-report-choice-badge-selected-correct" : "mcl-report-choice-badge-selected"}">${escapeHtml(t.selectedTag)}</span>` : ""
      ].join("");
      return `<div class="mcl-report-choice ${correct ? "mcl-report-choice-correct" : ""} ${selected && !correct ? "mcl-report-choice-selected" : ""} ${segmented ? "mcl-report-segment" : ""}">
        <span class="mcl-report-choice-label">${escapeHtml(option.label)}.</span>
        <span>${renderMath(option.latex, t.blank)}</span>
        <span class="mcl-report-choice-badges">${badges}</span>
      </div>`;
    }).join("");
    return `<div class="mcl-report-options-block ${segmented ? "mcl-report-options" : ""}"><div class="mcl-report-field-label">${escapeHtml(t.options)}</div><div class="mcl-report-choices">${choices}</div></div>`;
  }

  function visualHtml(item, reportLanguage = lang()) {
    if (!item.visual || typeof window.MCLQuizTool?.renderReportVisual !== "function") return "";
    try {
      const html = window.MCLQuizTool.renderReportVisual(item.visual, { lang: reportLanguage, mode: "report" });
      return html ? `<div class="mcl-report-question-visual">${html}</div>` : "";
    } catch {
      return "";
    }
  }

  function reportItemHtml(item, t, options = {}) {
    const resultClass = item.isCorrect ? "mcl-report-status-correct" : "mcl-report-status-incorrect";
    const resultText = item.isCorrect ? t.correctTag : t.wrongTag;
    const segmented = Boolean(options.segmented);
    return `<article class="mcl-report-item" data-item-index="${item.index}">
      <div class="mcl-report-item-head">
        <span>${escapeHtml(t.question)} ${item.index}${item.topicLabel ? ` \u00b7 ${escapeHtml(item.topicLabel)}` : ""}</span>
        <span class="mcl-report-status ${resultClass}">${escapeHtml(resultText)}</span>
      </div>
      <div class="mcl-report-item-body">
        <div class="mcl-report-segment mcl-report-question-block">
          <div class="mcl-report-field-label">${escapeHtml(t.question)}</div>
          <div class="mcl-report-question-text">${renderMath(item.questionLatex || item.questionText, t.blank)}</div>
          ${visualHtml(item, options.language)}
        </div>
        ${optionsHtml(item, t, segmented)}
        <div class="mcl-report-segment mcl-report-answer-block">
          <div class="mcl-report-answer-row"><span>${escapeHtml(t.yourAnswer)}</span><strong>${renderMath(item.selectedAnswerLatex, t.blank)}</strong></div>
          <div class="mcl-report-answer-row"><span>${escapeHtml(t.correctAnswer)}</span><strong>${renderMath(item.correctAnswerLatex, t.blank)}</strong></div>
          ${item.suggestion ? `<div class="mcl-report-suggestion"><span>${escapeHtml(t.suggestion)}</span><p>${escapeHtml(item.suggestion)}</p></div>` : ""}
        </div>
      </div>
    </article>`;
  }

