  function createPage(host, model, kind = "details") {
    const page = document.createElement("section");
    page.className = `mcl-pdf-page mcl-pdf-${kind}-page`;
    const content = document.createElement("div");
    content.className = "mcl-pdf-page-content";
    if (kind === "details") {
      const heading = document.createElement("h2");
      heading.className = "mcl-pdf-section-title";
      heading.textContent = model.t.details;
      content.appendChild(heading);
    }
    const footer = document.createElement("div");
    footer.className = "mcl-pdf-footer";
    footer.innerHTML = `<span>${escapeHtml(model.t.generated)}</span><span data-page-number></span>`;
    page.append(content, footer);
    host.appendChild(page);
    return { page, content };
  }

  function renderMathElements(root) {
    root.querySelectorAll("[data-latex]").forEach(element => {
      const latex = element.dataset.latex || "";
      if (!window.katex) {
        element.textContent = latex;
        return;
      }
      try {
        window.katex.render(latex, element, { throwOnError: false, displayMode: false });
      } catch {
        element.textContent = latex;
      }
    });
  }

  function withTimeout(promise, timeoutMs, message) {
    let timer = null;
    const timeout = new Promise((_, reject) => {
      timer = window.setTimeout(() => reject(new Error(message)), timeoutMs);
    });
    return Promise.race([promise, timeout]).finally(() => window.clearTimeout(timer));
  }

  async function waitForAssets(root) {
    if (document.fonts?.ready) {
      try {
        await withTimeout(document.fonts.ready, 5000, "Timed out while waiting for report fonts.");
      } catch {
        // Font fallback remains usable.
      }
    }
    const imagesReady = Promise.all([...root.querySelectorAll("img")].map(image => {
      if (image.complete) return image.decode?.().catch(() => {}) || Promise.resolve();
      return new Promise(resolve => {
        image.addEventListener("load", resolve, { once: true });
        image.addEventListener("error", resolve, { once: true });
      });
    }));
    try {
      await withTimeout(imagesReady, 5000, "Timed out while waiting for report images.");
    } catch {
      // Broken optional images must not leave the result page locked.
    }
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  }

  function pageOverflows(content) {
    return content.scrollHeight > content.clientHeight + 1;
  }

  function continuationCard(item, model) {
    const article = document.createElement("article");
    article.className = "item pdf-item pdf-continuation";
    article.innerHTML = `<div class="item-head"><span>#${item.index} \u00b7 ${escapeHtml(model.t.continued)}</span></div><div class="qa"></div>`;
    return article;
  }

  async function appendOversizedItem(host, model, item, sourceArticle, pageState) {
    const segments = [...sourceArticle.querySelectorAll(":scope > .qa > .pdf-segment, :scope > .qa > .pdf-options > .choices > .pdf-segment")];
    let current = pageState;
    let card = continuationCard(item, model);
    current.content.appendChild(card);
    let body = card.querySelector(".qa");

    for (const segment of segments) {
      const clone = segment.cloneNode(true);
      body.appendChild(clone);
      await new Promise(resolve => requestAnimationFrame(resolve));
      if (!pageOverflows(current.content)) continue;

      clone.remove();
      if (!body.children.length) {
        body.appendChild(segment.cloneNode(true));
        continue;
      }
      current = createPage(host, model, "details");
      card = continuationCard(item, model);
      current.content.appendChild(card);
      body = card.querySelector(".qa");
      body.appendChild(segment.cloneNode(true));
    }
    return current;
  }

  async function buildPdfPages(model = buildReportModel()) {
    const host = document.createElement("div");
    host.className = "mcl-pdf-host";
    host.setAttribute("aria-hidden", "true");
    const style = document.createElement("style");
    style.textContent = reportCss(true);
    host.appendChild(style);
    document.body.appendChild(host);

    const summaryPage = createPage(host, model, "summary");
    summaryPage.content.innerHTML = summaryHtml(model);

    const staging = document.createElement("div");
    staging.className = "mcl-pdf-staging";
    staging.innerHTML = model.attempts.map(item => reportItemHtml(item, model.t, { segmented: true, language: model.language })).join("");
    host.appendChild(staging);
    renderMathElements(host);
    await waitForAssets(host);

    let current = createPage(host, model, "details");
    for (const [index, source] of [...staging.querySelectorAll(".pdf-item")].entries()) {
      const item = model.attempts[index];
      const clone = source.cloneNode(true);
      current.content.appendChild(clone);
      await new Promise(resolve => requestAnimationFrame(resolve));
      if (!pageOverflows(current.content)) continue;

      clone.remove();
      const hasItems = Boolean(current.content.querySelector(".pdf-item"));
      if (hasItems) current = createPage(host, model, "details");
      current.content.appendChild(clone);
      await new Promise(resolve => requestAnimationFrame(resolve));
      if (!pageOverflows(current.content)) continue;

      clone.remove();
      current = await appendOversizedItem(host, model, item, source, current);
    }
    staging.remove();

    const pages = [...host.querySelectorAll(".mcl-pdf-page")];
    pages.forEach((page, index) => {
      const label = model.t.page.replace("{current}", String(index + 1)).replace("{total}", String(pages.length));
      page.querySelector("[data-page-number]").textContent = label;
    });
    await waitForAssets(host);
    return { host, pages, model };
  }

  function loadScriptOnce(src, ready) {
    if (ready()) return Promise.resolve();
    const existing = [...document.scripts].find(script => script.src === src);
    if (existing) {
      return new Promise((resolve, reject) => {
        if (ready()) resolve();
        else {
          existing.addEventListener("load", resolve, { once: true });
          existing.addEventListener("error", reject, { once: true });
        }
      });
    }
    return new Promise((resolve, reject) => {
      const script = document.createElement("script");
      script.src = src;
      script.async = true;
      script.addEventListener("load", () => ready() ? resolve() : reject(new Error(`Dependency did not initialize: ${src}`)), { once: true });
      script.addEventListener("error", () => reject(new Error(`Could not load dependency: ${src}`)), { once: true });
      document.head.appendChild(script);
    });
  }

  async function ensurePdfDependencies() {
    await loadScriptOnce(dependencyUrls.html2canvas, () => typeof window.html2canvas === "function");
    await loadScriptOnce(dependencyUrls.jspdf, () => typeof window.jspdf?.jsPDF === "function");
  }

  function setPdfButtonsBusy(busy, label = "") {
    document.querySelectorAll("[data-report-download]").forEach(button => {
      button.disabled = busy;
      button.setAttribute("aria-busy", busy ? "true" : "false");
      const text = button.querySelector("[data-report-button-text]");
      if (text) text.textContent = label || copy().downloadPdf;
      else button.textContent = label || copy().downloadPdf;
    });
  }

  function setPdfProgress(page, total) {
    setPdfButtonsBusy(true, copy().generatingPage(page, total));
  }

  function downloadBlob(blob, filename) {
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = filename;
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    window.setTimeout(() => URL.revokeObjectURL(url), 2000);
  }

  async function renderPdfPages(result) {
    const { jsPDF } = window.jspdf;
    const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4", compress: true });
    for (let index = 0; index < result.pages.length; index += 1) {
      setPdfProgress(index + 1, result.pages.length);
      const canvas = await withTimeout(window.html2canvas(result.pages[index], {
        scale: 2,
        backgroundColor: "#ffffff",
        logging: false,
        useCORS: true,
        imageTimeout: 15000,
        width: PDF_PAGE_WIDTH,
        height: PDF_PAGE_HEIGHT,
        windowWidth: PDF_PAGE_WIDTH,
        windowHeight: PDF_PAGE_HEIGHT,
        scrollX: 0,
        scrollY: 0
      }), 45000, `Timed out while rendering PDF page ${index + 1}.`);
      if (index > 0) pdf.addPage("a4", "portrait");
      const image = canvas.toDataURL("image/jpeg", 0.94);
      pdf.addImage(image, "JPEG", 0, 0, 210, 297, undefined, "FAST");
      canvas.width = 1;
      canvas.height = 1;
      await new Promise(resolve => window.setTimeout(resolve, 0));
    }
    const blob = pdf.output("blob");
    if (!(blob instanceof Blob) || blob.type !== "application/pdf" || blob.size < 5) {
      throw new Error("jsPDF did not produce a valid PDF blob.");
    }
    const signature = await blob.slice(0, 4).text();
    if (signature !== "%PDF") throw new Error("Generated file does not contain a PDF signature.");
    return blob;
  }

  function showPdfError(error) {
    console.error("MathComplete Lab PDF export failed:", error);
    document.querySelectorAll(".mcl-report-error").forEach(node => node.remove());
    document.querySelectorAll("[data-report-download]").forEach(button => {
      const panel = document.createElement("div");
      panel.className = "mcl-report-error";
      panel.setAttribute("role", "alert");
      panel.style.cssText = "display:flex;flex-wrap:wrap;align-items:center;gap:10px;width:100%;margin-top:10px;color:var(--danger,#b42318);font-weight:600";
      const message = document.createElement("span");
      message.textContent = copy().pdfError;
      const fallback = document.createElement("button");
      fallback.type = "button";
      fallback.className = "ghost";
      fallback.textContent = copy().downloadHtml;
      fallback.addEventListener("click", downloadHtmlReport, { once: true });
      panel.append(message, fallback);
      button.parentElement?.appendChild(panel);
    });
  }

  async function downloadPdfReport() {
    if (pdfTask) return pdfTask;
    const model = buildReportModel();
    if (!model.attempts.length) {
      alert(model.t.noAttempts);
      return null;
    }
    document.querySelectorAll(".mcl-report-error").forEach(node => node.remove());
    setPdfButtonsBusy(true, model.t.generating);
    pdfTask = (async () => {
      let pagesResult = null;
      try {
        await ensurePdfDependencies();
        pagesResult = await buildPdfPages(model);
        const blob = await renderPdfPages(pagesResult);
        const date = new Date().toISOString().slice(0, 10);
        downloadBlob(blob, `${slug(model.tool)}-report-${date}.pdf`);
        return blob;
      } catch (error) {
        showPdfError(error);
        throw error;
      } finally {
        pagesResult?.host?.remove();
        setPdfButtonsBusy(false);
        pdfTask = null;
      }
    })();
    return pdfTask;
  }

  function downloadHtmlReport() {
    const model = buildReportModel();
    if (!model.attempts.length) {
      alert(model.t.noAttempts);
      return null;
    }
    const blob = new Blob([reportHtml(model)], { type: "text/html;charset=utf-8" });
    const date = new Date().toISOString().slice(0, 10);
    downloadBlob(blob, `${slug(model.tool)}-report-${date}.html`);
    return blob;
  }

  function downloadReport() {
    return downloadPdfReport().catch(() => null);
  }

