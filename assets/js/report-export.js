  function safe(value) {
    if (value === null || value === undefined) return "";
    return String(value);
  }

  function escapeHtml(value) {
    return safe(value)
      .replaceAll("&", "&amp;")
      .replaceAll("<", "&lt;")
      .replaceAll(">", "&gt;")
      .replaceAll('"', "&quot;")
      .replaceAll("'", "&#039;");
  }

  function attr(value) {
    return escapeHtml(value).replaceAll("\n", " ");
  }

  function stripHtml(value) {
    const tmp = document.createElement("div");
    tmp.innerHTML = safe(value);
    return tmp.textContent || tmp.innerText || "";
  }

  function formatDate(value) {
    try {
      return new Intl.DateTimeFormat(lang() === "zh" ? "zh-CN" : "en-US", {
        year: "numeric",
        month: "short",
        day: "2-digit",
        hour: "2-digit",
        minute: "2-digit"
      }).format(new Date(value));
    } catch {
      return safe(value);
    }
  }

  function formatDuration(seconds, language = lang()) {
    const total = Math.max(0, Math.round(Number(seconds) || 0));
    const minutes = Math.floor(total / 60);
    const remainder = total % 60;
    if (language === "zh") return minutes ? `${minutes}\u5206${remainder}\u79d2` : `${remainder}\u79d2`;
    return minutes ? `${minutes} min ${remainder} sec` : `${remainder} sec`;
  }

  function slug(value) {
    return safe(value)
      .toLowerCase()
      .replace(/[^a-z0-9\u4e00-\u9fa5]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 60) || "mathcomplete-report";
  }

  function reportIdentifier(gameId, date) {
    const value = new Date(date);
    const pad = number => String(number).padStart(2, "0");
    const compact = `${value.getFullYear()}${pad(value.getMonth() + 1)}${pad(value.getDate())}-${pad(value.getHours())}${pad(value.getMinutes())}${pad(value.getSeconds())}`;
    let hash = 2166136261;
    for (const character of safe(gameId)) {
      hash ^= character.charCodeAt(0);
      hash = Math.imul(hash, 16777619);
    }
    return `MCL-${compact}-${(hash >>> 0).toString(36).toUpperCase().padStart(6, "0").slice(0, 6)}`;
  }

