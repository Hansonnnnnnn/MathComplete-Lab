create or replace function public.mfa_requirement_satisfied()
returns boolean
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
  select array[coalesce(auth.jwt() ->> 'aal', 'aal1')] <@ (
    select case when count(id) > 0 then array['aal2'] else array['aal1', 'aal2'] end
    from auth.mfa_factors
    where user_id = auth.uid() and status = 'verified'
  );
$$;

create or replace function public.accept_current_consents(
  p_terms_version text,
  p_privacy_version text,
  p_age_confirmed boolean
)
returns public.user_consents
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare result public.user_consents;
begin
  if auth.uid() is null or p_age_confirmed is not true then raise exception 'consent_required'; end if;
  insert into public.user_consents (user_id, terms_version, privacy_version, age_confirmed, accepted_at)
  values (auth.uid(), left(p_terms_version, 40), left(p_privacy_version, 40), true, now())
  on conflict (user_id) do update set terms_version = excluded.terms_version, privacy_version = excluded.privacy_version, age_confirmed = true, accepted_at = now()
  returning * into result;
  return result;
end;
$$;

create or replace function public.record_attempt(p_attempt jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  uid uuid := auth.uid();
  client_id uuid;
  attempt_row public.attempts;
  mistake_row public.mistakes;
  created_time timestamptz;
begin
  if uid is null then raise exception 'authentication_required'; end if;
  if not public.mfa_requirement_satisfied() then raise exception 'mfa_required'; end if;
  client_id := coalesce(nullif(p_attempt ->> 'client_attempt_id', '')::uuid, gen_random_uuid());
  begin created_time := coalesce(nullif(p_attempt ->> 'created_at', '')::timestamptz, now());
  exception when others then created_time := now(); end;

  insert into public.attempts (
    client_attempt_id, user_id, game_id, course, topic, difficulty, question_key,
    question_latex, question_text, correct_answer_latex, selected_answer_latex,
    is_correct, time_spent_seconds, created_at
  ) values (
    client_id, uid, left(coalesce(p_attempt ->> 'game_id', 'unknown-game'), 120),
    left(coalesce(p_attempt ->> 'course', ''), 120), left(coalesce(p_attempt ->> 'topic', ''), 160),
    left(coalesce(p_attempt ->> 'difficulty', ''), 80), left(coalesce(p_attempt ->> 'question_key', ''), 180),
    left(coalesce(p_attempt ->> 'question_latex', ''), 12000), left(coalesce(p_attempt ->> 'question_text', ''), 12000),
    left(coalesce(p_attempt ->> 'correct_answer_latex', ''), 8000), left(coalesce(p_attempt ->> 'selected_answer_latex', ''), 8000),
    coalesce((p_attempt ->> 'is_correct')::boolean, false),
    greatest(0, nullif(p_attempt ->> 'time_spent_seconds', '')::integer), created_time
  )
  on conflict (user_id, client_attempt_id) do nothing
  returning * into attempt_row;

  if attempt_row.id is null then
    select * into attempt_row from public.attempts where user_id = uid and client_attempt_id = client_id;
    return jsonb_build_object('attempt', to_jsonb(attempt_row), 'mistake', null, 'duplicate', true);
  end if;

  if not attempt_row.is_correct then
    insert into public.mistakes (
      user_id, game_id, course, topic, difficulty, question_key, question_latex,
      question_text, correct_answer_latex, last_selected_answer_latex, mistake_count,
      review_success_count, status, created_at, updated_at
    ) values (
      uid, attempt_row.game_id, attempt_row.course, attempt_row.topic, attempt_row.difficulty,
      attempt_row.question_key, attempt_row.question_latex, attempt_row.question_text,
      attempt_row.correct_answer_latex, attempt_row.selected_answer_latex, 1, 0, 'active', now(), now()
    )
    on conflict (user_id, game_id, question_key) do update set
      course = excluded.course, topic = excluded.topic, difficulty = excluded.difficulty,
      question_latex = excluded.question_latex, question_text = excluded.question_text,
      correct_answer_latex = excluded.correct_answer_latex,
      last_selected_answer_latex = excluded.last_selected_answer_latex,
      mistake_count = public.mistakes.mistake_count + 1,
      review_success_count = 0, status = 'active', updated_at = now()
    returning * into mistake_row;
  end if;
  return jsonb_build_object('attempt', to_jsonb(attempt_row), 'mistake', to_jsonb(mistake_row));
end;
$$;

