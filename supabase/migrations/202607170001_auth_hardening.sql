create or replace function public.handle_auth_user_created()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  accepted timestamptz;
begin
  insert into public.profiles (id, email, display_name)
  values (new.id, new.email, left(coalesce(new.raw_user_meta_data ->> 'display_name', split_part(coalesce(new.email, ''), '@', 1)), 80))
  on conflict (id) do update set email = excluded.email;

  insert into public.account_entitlements (user_id) values (new.id)
  on conflict (user_id) do nothing;

  if coalesce((new.raw_user_meta_data ->> 'age_confirmed')::boolean, false) then
    begin
      accepted := coalesce((new.raw_user_meta_data ->> 'consent_accepted_at')::timestamptz, now());
    exception when others then
      accepted := now();
    end;
    insert into public.user_consents (user_id, terms_version, privacy_version, age_confirmed, accepted_at)
    values (
      new.id,
      left(coalesce(new.raw_user_meta_data ->> 'terms_version', 'unknown'), 40),
      left(coalesce(new.raw_user_meta_data ->> 'privacy_version', 'unknown'), 40),
      true,
      accepted
    )
    on conflict (user_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_auth_user_created();

