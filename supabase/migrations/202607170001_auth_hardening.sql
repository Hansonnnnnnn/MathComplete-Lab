  topic text not null default '',
  difficulty text not null default '',
  question_key text not null,
  question_latex text not null default '',
  question_text text not null default '',
  correct_answer_latex text not null default '',
  selected_answer_latex text not null default '',
  is_correct boolean not null default false,
  time_spent_seconds integer check (time_spent_seconds is null or time_spent_seconds >= 0),
