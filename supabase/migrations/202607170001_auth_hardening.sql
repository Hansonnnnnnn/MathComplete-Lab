alter table public.profiles add column if not exists created_at timestamptz not null default now();
alter table public.profiles add column if not exists updated_at timestamptz not null default now();

create table if not exists public.account_entitlements (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan text not null default 'free' check (plan in ('free', 'plus')),
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'profiles' and column_name = 'plan'
  ) then
    insert into public.account_entitlements (user_id, plan)
    select id, case when plan = 'plus' then 'plus' else 'free' end
    from public.profiles
    on conflict (user_id) do nothing;
    alter table public.profiles drop column plan;
  end if;
end $$;

insert into public.account_entitlements (user_id)
select id from auth.users
on conflict (user_id) do nothing;

create table if not exists public.user_consents (
  user_id uuid primary key references auth.users(id) on delete cascade,
  terms_version text not null,
  privacy_version text not null,
  age_confirmed boolean not null check (age_confirmed),
  accepted_at timestamptz not null default now()
);

