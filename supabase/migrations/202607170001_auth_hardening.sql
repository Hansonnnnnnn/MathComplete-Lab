do $$
declare table_name text;
begin
  foreach table_name in array array['profiles','account_entitlements','user_consents','attempts','mistakes','favorite_tools'] loop
    execute format('drop policy if exists %I on public.%I', table_name || '_mfa_access', table_name);
    execute format('create policy %I on public.%I as restrictive for all to authenticated using (public.mfa_requirement_satisfied()) with check (public.mfa_requirement_satisfied())', table_name || '_mfa_access', table_name);
  end loop;
end $$;

